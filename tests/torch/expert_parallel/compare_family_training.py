"""Compare observed CE training and exact same-topology checkpoint continuation."""

import argparse
import json
from pathlib import Path

import torch


def _records(directory, rank):
    items = [json.loads(line) for line in (directory / f"rank{rank}.jsonl").read_text().splitlines()]
    records = {item["step"]: item for item in items}
    assert len(items) == len(records), (directory, rank, "duplicate steps from mixed runs")
    return records


def compare(root: Path, *, resume: bool = False, activation_checkpoint: bool = False) -> dict:
    """Validate traces and report CE differences without inventing a convergence threshold.

    Args:
        root: Directory generated by prepare_family_validation and the observed Trainer.
        resume: Require all six runs resumed from global_step_5 in resume-epN-mode directories.
        activation_checkpoint: Compare full recomputation runs in ac-epN-fused directories.

    Returns:
        Loss trajectories, numerical differences and exact continuation results.
    """
    report = {"loss": {}, "comparisons": {}, "resume": {}, "activation_checkpoint": {}}
    for ep_size in (1, 2):
        traces = {}
        for mode in ("bf16", "mxfp8", "fused"):
            name = f"ep{ep_size}-{mode}"
            directory = root / f"trace-{name}"
            ranks = [_records(directory, rank) for rank in range(ep_size)]
            _check_mode(root, name, mode, ranks, resume, activation_checkpoint)
            traces[mode] = ranks
            report["loss"][name] = [sum(rank[step]["loss"] for rank in ranks) / ep_size
                                    for step in range(1, 11)]
            if resume:
                report["resume"][name] = "steps 6-10: exact loss, weights, batches and RNG"
            if activation_checkpoint and mode == "fused":
                report["activation_checkpoint"][name] = "steps 1-10: exact loss, gradients norms, weights and RNG"
        for left, right in (("fused", "mxfp8"), ("fused", "bf16"), ("mxfp8", "bf16")):
            for rank in range(ep_size):
                for step in range(1, 11):
                    assert traces[left][rank][step]["batches"] == traces[right][rank][step]["batches"]
            actual, reference = (report["loss"][f"ep{ep_size}-{mode}"] for mode in (left, right))
            report["comparisons"][f"ep{ep_size}-{left}-vs-{right}"] = {
                "max_abs_loss": max(abs(a - b) for a, b in zip(actual, reference)),
                "max_relative_loss": max(abs(a - b) / abs(b) for a, b in zip(actual, reference)),
            }
    return report


def _check_mode(root, name, mode, ranks, resume, activation_checkpoint):
    for rank, records in enumerate(ranks):
        assert set(records) == set(range(1, 11)), (name, rank, list(records))
        if mode != "bf16":
            assert records[10]["gmm_calls"] > 0, name
        if mode == "fused":
            assert records[10]["fused_forward"] > 0 and records[10]["fused_backward"] > 0, name
        if resume:
            _compare_resume(root, name, rank, records)
        if activation_checkpoint and mode == "fused":
            recomputed = _records(root / f"ac-{name}", rank)
            assert set(recomputed) == set(records)
            assert recomputed[10]["fused_forward"] > records[10]["fused_forward"]
            _compare_steps(root / f"ac-{name}", root / f"trace-{name}", rank, recomputed, records)


def _compare_resume(root, name, rank, original):
    directory = root / f"resume-{name}"
    resumed = _records(directory, rank)
    begin = json.loads((directory / f"rank{rank}-begin.json").read_text())
    assert begin == {"step": 5, "rng": original[5]["rng"]}, (name, rank, "restored RNG")
    assert set(resumed) == set(range(6, 11)), (name, rank, "resumed steps")
    _compare_steps(directory, root / f"trace-{name}", rank, resumed, original)


def _compare_steps(directory, reference_directory, rank, actual_records, original):
    for step, record in actual_records.items():
        for field in ("loss", "grad_norm", "batches", "rng"):
            assert record[field] == original[step][field], (directory.name, rank, step, field)
        filename = f"rank{rank}-step{step}.pt"
        actual = torch.load(directory / filename, map_location="cpu", weights_only=True)
        expected = torch.load(reference_directory / filename, map_location="cpu", weights_only=True)
        assert actual.keys() == expected.keys()
        for parameter in actual:
            torch.testing.assert_close(actual[parameter], expected[parameter], rtol=0, atol=0,
                                       msg=f"{directory.name} rank={rank} step={step} {parameter}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", type=Path)
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--activation-checkpoint", action="store_true")
    arguments = parser.parse_args()
    print(json.dumps(compare(arguments.root, resume=arguments.resume,
                             activation_checkpoint=arguments.activation_checkpoint), indent=2))
